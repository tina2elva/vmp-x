    str     x9, [sp, #VM_CTX_SCRATCH]
    mov     w9, #VM_SCRATCH_SIZE
    str     w9, [sp, #VM_CTX_SCRATCHLEN]
    str     xzr, [sp, #(VM_CTX_OFF_REGS + 8*33)]

    /* ---- ??? SP?????vm_run ?????? VM_MARGIN ??---- */
